DECLARE bad TEXT;
BEGIN
    SELECT string_agg(p.resort_key || ' [' || COALESCE(m.n::text, '0') || ' matches]', '; ') INTO bad
    FROM resort_location_patterns p
    CROSS JOIN LATERAL (SELECT COUNT(*) AS n FROM locations l WHERE l.location_name ILIKE p.name_pattern) m
    WHERE m.n <> 1;
